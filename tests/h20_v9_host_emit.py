#!/usr/bin/env python3
"""Build and drive tests/h20_v9_host_emitter.cpp (live SM90 host heuristics).

The emitter is compiled against a generated copy of
csrc/jit_kernels/heuristics/sm90_mega_moe.hpp whose only edit is the include
block: the heavyweight torch / DeepJIT-runtime chain pulled in through
``sm90.hpp`` + ``utils/math.hpp`` is replaced by a 6-line stub that provides the
three symbols this header actually uses (ceil_div, align,
SM90ArchSpec::smem_capacity).  Every heuristic line -- spec parsing, the
WEAVE_* env mapping, select_mega_moe_sm90, the SMEM budget and the JIT define
emitter -- is compiled verbatim.

The kernel instantiation format literal is extracted verbatim from
SM90FP8MegaMoERuntime::compile_only, and the argument list that follows it is
compared against the emitter's mirror, so a drift in either fails loudly.
"""
from __future__ import annotations

import functools
import platform
import subprocess
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SM90_HEADER = ROOT / "csrc/jit_kernels/heuristics/sm90_mega_moe.hpp"
IMPL_HEADER = ROOT / "csrc/jit_kernels/impls/sm90_fp8_mega_moe.hpp"
EMITTER_SRC = ROOT / "tests/h20_v9_host_emitter.cpp"
SHIM_DIRS = (ROOT / "tests/h20_v9_host_shim",)
INCLUDE_FALLBACKS = (
    ROOT.parent / "weave_unified_cpp" / "third-party" / "cutlass" / "include",
    ROOT.parent / "weave_unified_cpp" / "third-party" / "deep_jit" / "include",
)
WSL_CUDA_INCLUDES = ("/usr/local/cuda/include",
                     "/usr/local/cuda/targets/x86_64-linux/include/cccl")

INCLUDE_OLD = ('#include "../../utils/math.hpp"\n#include "sm90.hpp"\n')
STUB = """#pragma once
// Generated by tests/h20_v9_host_emit.py -- do not edit.
namespace deep_gemm {
template <typename T> static T ceil_div(const T& a, const T& b) { return (a + b - 1) / b; }
template <typename T> static constexpr T align(const T& a, const T& b) { return ceil_div(a, b) * b; }
struct SM90ArchSpec { static constexpr int smem_capacity = 232448; };
}  // namespace deep_gemm
"""

# Argument list of the instantiation std::format in compile_only; the emitter
# passes the same fields in the same order (see render() in the .cpp).
EXPECTED_ARGS = [
    "kernel_symbol",
    "args.num_max_tokens_per_rank",
    "args.hidden, args.intermediate_hidden",
    "args.num_experts, args.num_topk",
    "args.config.num_experts_per_wave",
    "args.config.block_m, args.config.block_n, args.config.block_k",
    "args.config.num_max_pool_tokens",
    "args.config.num_padded_sf_pool_tokens",
    "args.config.sf_pool_stride_tokens",
    "args.config.num_stages",
    "args.config.num_dispatch_threads, args.config.num_non_epilogue_threads, args.config.num_epilogue_threads",
    "args.config.num_sms, args.num_ranks",
    "to_string(args.activation_clamp)",
    'args.fast_math ? "true" : "false"',
    'args.config.swap_ab ? "true" : "false"',
    'args.bf16_scaled_accum ? "true" : "false"',
    "phase_template_args));",
]

WINDOWS = platform.system() == "Windows"


def wsl_path(p: Path | str) -> str:
    s = str(p)
    if WINDOWS and len(s) > 1 and s[1] == ":":
        return "/mnt/" + s[0].lower() + s[2:].replace("\\", "/")
    return s


@functools.lru_cache(maxsize=1)
def _host_cc_cached() -> tuple[str, ...]:
    if WINDOWS:
        proc = subprocess.run(["wsl", "-e", "bash", "-lc", "command -v g++"],
                              capture_output=True, text=True, encoding="utf-8",
                              errors="replace", timeout=120)
        found = (proc.stdout or "").strip()
        if proc.returncode != 0 or not found:
            raise SystemExit("no host g++ (WSL) available for the H20 host emitter")
        return ("wsl", "-e", found)
    return ("g++",)


def _host_cc() -> list[str]:
    return list(_host_cc_cached())


def extract_instantiate_format() -> str:
    text = IMPL_HEADER.read_text(encoding="utf-8")
    start_tok = 'prof_defs + agy_defs + std::format(R"('
    if text.count(start_tok) != 1:
        raise SystemExit("compile_only format literal marker is not unique")
    start = text.index(start_tok) + len(start_tok)
    end = text.index(')",\n', start)
    literal = text[start:end]
    tail = text[end + len(')",\n'):]
    lines = [ln.strip().rstrip(",") for ln in tail.splitlines()]
    got = [ln for ln in lines[:len(EXPECTED_ARGS)]]
    want = [a.rstrip(",") for a in EXPECTED_ARGS]
    if got != want:
        raise SystemExit("compile_only argument list drifted from the emitter mirror:\n"
                         f"  got  {got}\n  want {want}")
    if literal.count("{}") != 24:
        raise SystemExit(f"compile_only format literal has {literal.count('{}')} fields, expected 24")
    return literal


def write_generated(build_dir: Path) -> None:
    text = SM90_HEADER.read_text(encoding="utf-8")
    if text.count(INCLUDE_OLD) != 1:
        raise SystemExit("sm90_mega_moe.hpp include block changed; update h20_v9_host_emit.py")
    text = text.replace(INCLUDE_OLD, '#include "sm90_host_stub.hpp"\n')
    text = text.replace('#include "../../utils/', '#include "utils/')
    (build_dir / "sm90_mega_moe_host.hpp").write_text(text, encoding="utf-8", newline="\n")
    (build_dir / "sm90_host_stub.hpp").write_text(STUB, encoding="utf-8", newline="\n")
    literal = extract_instantiate_format()
    (build_dir / "h20_v9_instantiate_fmt.hpp").write_text(
        "#pragma once\n// Generated by tests/h20_v9_host_emit.py from compile_only -- do not edit.\n"
        f'#define H20_V9_INSTANTIATE_FMT R"H20V9({literal})H20V9"\n',
        encoding="utf-8", newline="\n")


def include_dirs() -> list[Path]:
    dirs = [ROOT / "deep_gemm/include", ROOT / "csrc"]
    for name in ("cutlass", "deep_jit"):
        local = ROOT / "third-party" / name / "include"
        if local.is_dir() and any(local.iterdir()):
            dirs.append(local)
    if len(dirs) == 2:
        dirs.extend(p for p in INCLUDE_FALLBACKS if p.is_dir())
    return dirs


def _inputs_digest(build_dir: Path) -> str:
    import hashlib
    h = hashlib.sha256()
    for path in sorted([*build_dir.glob("*.hpp"), EMITTER_SRC, Path(__file__),
                        *ROOT.glob("deep_gemm/include/deep_gemm/layout/*.cuh"),
                        *ROOT.glob("deep_gemm/include/deep_gemm/scheduler/weave_*.cuh")]):
        h.update(path.name.encode())
        h.update(path.read_bytes())
    return h.hexdigest()


def build_emitter(build_dir: Path) -> Path:
    """Build once per input digest (the heuristics header, the emitter, layouts)."""
    build_dir.mkdir(parents=True, exist_ok=True)
    write_generated(build_dir)
    binary = build_dir / "h20_v9_host_emitter"
    stamp = build_dir / "h20_v9_host_emitter.sha256"
    digest = _inputs_digest(build_dir)
    if binary.exists() and stamp.exists() and stamp.read_text().strip() == digest:
        return binary
    cc = _host_cc()
    conv = wsl_path if WINDOWS else str
    cmd = [*cc, "-std=c++20", "-O1", "-pthread", "-w", "-I", conv(build_dir)]
    for inc in [*include_dirs(), *SHIM_DIRS]:
        cmd += ["-I", conv(inc)]
    for inc in WSL_CUDA_INCLUDES if WINDOWS else ():
        cmd += ["-I", inc]
    cmd += [conv(EMITTER_SRC), "-o", conv(binary), "-ldl"]
    proc = subprocess.run(cmd, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=900)
    if proc.returncode != 0:
        raise SystemExit("H20 host emitter build failed:\n" + (proc.stdout or "") +
                         (proc.stderr or "")[-6000:])
    stamp.write_text(digest)
    return binary


def run_emitter(binary: Path, tokens: int, env: dict[str, str], out_prefix: Path,
                check: bool = True) -> dict:
    cc = _host_cc()
    run = ([cc[0], "-e", wsl_path(binary)] if WINDOWS else [str(binary)])
    run += [str(tokens), wsl_path(out_prefix) if WINDOWS else str(out_prefix)]
    run += [f"{k}={v}" for k, v in sorted(env.items())]
    # wsl.exe occasionally fails to start a process under heavy concurrency
    # (exit 0xFFFFFFFF with no output at all).  That is a launcher failure, not
    # a host-heuristic verdict, so retry it; a real DG_HOST_ASSERT always
    # prints the assertion text on stderr and is never retried.  A launcher
    # failure that persists raises instead of returning a non-zero code, so a
    # fail-closed probe (`returncode != 0`) can never pass on a launch glitch.
    for attempt in range(40):
        proc = subprocess.run(run, capture_output=True, text=True,
                              encoding="utf-8", errors="replace", timeout=300)
        # wsl.exe sometimes prints its own (UTF-16) service error on stdout with
        # the same 0xFFFFFFFF exit, so the criterion is the exit code plus the
        # absence of any host-heuristic output (assertion text or KEY=VALUE rows).
        launcher_failure = (proc.returncode in (-1, 0xFFFFFFFF)
                            and "Assertion" not in (proc.stderr or "")
                            and "SPEC_ENABLED=" not in (proc.stdout or ""))
        if not launcher_failure:
            break
        time.sleep(min(5.0, 0.5 * (attempt + 1)))
    else:
        raise RuntimeError(f"wsl.exe could not launch the H20 host emitter for env {env} "
                           f"(40 attempts, exit {proc.returncode}, no output)")
    out = {"returncode": proc.returncode, "stderr": (proc.stderr or "").strip()[-2000:]}
    for line in (proc.stdout or "").splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            out[k] = v
    if check and proc.returncode != 0:
        raise SystemExit(f"H20 host emitter rejected env {env}:\n{out['stderr']}")
    if proc.returncode == 0:
        out["defines"] = out.get("DEFINES", "").replace("|", "\n")
        out["kernels"] = out.get("KERNELS", "").split(",") if out.get("KERNELS") else []
        out["sources"] = {k: Path(f"{out_prefix}_{k}.cu") for k in out["kernels"]}
    return out


if __name__ == "__main__":
    import json
    import sys
    bdir = ROOT / "scratch/h20_v9_host_emit"
    b = build_emitter(bdir)
    env = dict(a.split("=", 1) for a in sys.argv[2:])
    r = run_emitter(b, int(sys.argv[1]) if len(sys.argv) > 1 else 1024, env, bdir / "probe")
    r.pop("sources", None)
    print(json.dumps(r, indent=1))
